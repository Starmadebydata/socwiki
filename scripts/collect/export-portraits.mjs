#!/usr/bin/env node
/**
 * Crop character portraits from device stats screenshots into public/characters/.
 *
 * Input:  content/raw/screenshots/{slug}-stats.png  (or -stats-v2.png)
 * Output: public/characters/{slug}.webp             (square avatar)
 *         public/characters/{slug}-art.webp         (wide detail art)
 *         src/data/character-images.ts              (slug → path map)
 *
 * Usage: node scripts/collect/export-portraits.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "../..");
const SHOT_DIR = path.join(ROOT, "content/raw/screenshots");
const OUT_DIR = path.join(ROOT, "public/characters");
const MAP_TS = path.join(ROOT, "src/data/character-images.ts");

fs.mkdirSync(OUT_DIR, { recursive: true });

function hasPythonPillow() {
  try {
    execFileSync("python3", ["-c", "from PIL import Image"], { stdio: "pipe" });
    return true;
  } catch {
    return false;
  }
}

function findStatsShot(slug) {
  const candidates = [
    path.join(SHOT_DIR, `${slug}-stats.png`),
    path.join(SHOT_DIR, `${slug}-stats-v2.png`),
    path.join(SHOT_DIR, `${slug}-before-skills.png`),
  ];
  return candidates.find((p) => fs.existsSync(p));
}

function listDeviceSlugs() {
  // Prefer device-ocr collected + any stats screenshots
  const fromCollected = fs
    .readdirSync(path.join(ROOT, "content/collected"))
    .filter((f) => f.endsWith(".json") && !f.startsWith("_"))
    .map((f) => {
      try {
        const d = JSON.parse(
          fs.readFileSync(path.join(ROOT, "content/collected", f), "utf8"),
        );
        return d.source === "device-ocr" ? d.slug : null;
      } catch {
        return null;
      }
    })
    .filter(Boolean);

  const fromShots = fs
    .readdirSync(SHOT_DIR)
    .map((f) => f.match(/^([a-z0-9-]+)-stats(?:-v2)?\.png$/i)?.[1])
    .filter(Boolean);

  return [...new Set([...fromCollected, ...fromShots])].sort();
}

function cropWithPython(src, outSquare, outArt) {
  const py = `
from PIL import Image
src = ${JSON.stringify(src)}
out_sq = ${JSON.stringify(outSquare)}
out_art = ${JSON.stringify(outArt)}
im = Image.open(src).convert("RGB")
w, h = im.size
# Client detail: full art on left ~45%, UI panel on right
art_right = min(w, int(w * 0.48))
art = im.crop((0, 0, art_right, h))
aw, ah = art.size
# Wide art for detail hero
wide = art.resize((720, max(1, int(720 * ah / aw))), Image.Resampling.LANCZOS)
wide.save(out_art, "WEBP", quality=82, method=6)
# Square avatar: center-upper body
side = min(aw, ah)
# bias toward character center (slightly right of left edge, slightly up)
cx = int(aw * 0.52)
cy = int(ah * 0.42)
x0 = max(0, min(aw - side, cx - side // 2))
y0 = max(0, min(ah - side, cy - side // 2))
sq = art.crop((x0, y0, x0 + side, y0 + side)).resize((512, 512), Image.Resampling.LANCZOS)
sq.save(out_sq, "WEBP", quality=85, method=6)
print("ok", out_sq)
`;
  execFileSync("python3", ["-c", py], { stdio: ["ignore", "pipe", "inherit"] });
}

function main() {
  if (!hasPythonPillow()) {
    console.error("Pillow required: pip3 install pillow");
    process.exit(1);
  }

  const slugs = listDeviceSlugs();
  const map = {};
  let n = 0;

  for (const slug of slugs) {
    const src = findStatsShot(slug);
    if (!src) {
      console.log(`skip ${slug} (no stats screenshot)`);
      continue;
    }
    const outSq = path.join(OUT_DIR, `${slug}.webp`);
    const outArt = path.join(OUT_DIR, `${slug}-art.webp`);
    try {
      cropWithPython(src, outSq, outArt);
      map[slug] = {
        portrait: `/characters/${slug}.webp`,
        art: `/characters/${slug}-art.webp`,
      };
      n++;
      console.log(`✓ ${slug}`);
    } catch (e) {
      console.error(`✗ ${slug}:`, e.message || e);
    }
  }

  const lines = [];
  lines.push(`/** Auto-generated by scripts/collect/export-portraits.mjs */`);
  lines.push(``);
  lines.push(`export type CharacterImageSet = {`);
  lines.push(`  portrait: string;`);
  lines.push(`  art?: string;`);
  lines.push(`};`);
  lines.push(``);
  lines.push(
    `export const CHARACTER_IMAGES: Record<string, CharacterImageSet> = ${JSON.stringify(map, null, 2)};`,
  );
  lines.push(``);
  lines.push(`export function getCharacterImage(slug: string): CharacterImageSet | undefined {`);
  lines.push(`  return CHARACTER_IMAGES[slug];`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`export function hasCharacterPortrait(slug: string): boolean {`);
  lines.push(`  return Boolean(CHARACTER_IMAGES[slug]?.portrait);`);
  lines.push(`}`);
  lines.push(``);

  fs.writeFileSync(MAP_TS, lines.join("\n"));
  console.log(`\nExported ${n} portraits → ${OUT_DIR}`);
  console.log(`Wrote ${MAP_TS}`);
}

main();
