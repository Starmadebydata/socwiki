const TOP20 = getTop20Map();
const AUTO = getAutoRefinedMap();
const DEVICE = getDeviceOcrMap();
const DEVICE_CHARS = getDeviceOcrCharacterMap();

function applyPartial(
  c: Character,
  a: Partial<Character> | undefined,
): Character {
  if (!a) return c;
  return {
    ...c,
    role: (a.role as Character["role"]) || c.role,
    factions: a.factions?.length ? a.factions : c.factions,
    move: a.move ?? c.move,
    highJump: a.highJump ?? c.highJump,
    lowJump: a.lowJump ?? c.lowJump,
    summary: a.summary || c.summary,
    pros: a.pros?.length ? a.pros : c.pros,
    howToUse: a.howToUse || c.howToUse,
    build: a.build
      ? {
          basicAttack: a.build.basicAttack || c.build.basicAttack,
          reaction: a.build.reaction || c.build.reaction,
          skills: a.build.skills?.length ? a.build.skills : c.build.skills,
          weaponSlug: a.build.weaponSlug || c.build.weaponSlug,
          trinketSlug: a.build.trinketSlug || c.build.trinketSlug,
          tarotSlug: a.build.tarotSlug || c.build.tarotSlug,
        }
      : c.build,
    skillPriority:
      a.skillPriority && a.skillPriority.length >= 3
        ? a.skillPriority
        : c.skillPriority,
    starPriority: a.starPriority || c.starPriority,
    lastUpdated: a.lastUpdated || c.lastUpdated,
  };
}

function applyAuto(c: Character): Character {
  return applyPartial(c, AUTO[c.slug]);
}

function applyDevice(c: Character): Character {
  return applyPartial(c, DEVICE[c.slug]);
}

/**
 * Merge order:
 * 1) rawCharacters (seed roster)
 * 2) AUTO_REFINED structured scrape (skills/NRG/CD/build)
 * 3) DEVICE_OCR client tooltips (wins over auto for same slug)
 * 4) TOP20 hand-refined full override (wins for meta cores)
 * 5) device-only units not in seed (minions / generics from capture)
 */
const refinedCore: Character[] = rawCharacters.map((c) => {
  const withAuto = applyAuto(c);
  const withDevice = applyDevice(withAuto);
  return TOP20[c.slug] ?? withDevice;
});

const seedSlugs = new Set(rawCharacters.map((c) => c.slug));
const deviceOnly: Character[] = Object.values(DEVICE_CHARS).filter(
  (c) => !seedSlugs.has(c.slug),
);

export const characters: Character[] = [...refinedCore, ...deviceOnly];

export function getAllCharacters(): Character[] {
  return characters;
}

export function getCharacterBySlug(slug: string): Character | undefined {
  return characters.find((c) => c.slug === slug);
}

export function getCharactersByRole(role: Role): Character[] {
  return characters.filter((c) => c.role === role);
}

export function getCharacterMap(): Record<string, Character> {
  return Object.fromEntries(characters.map((c) => [c.slug, c]));
}

const TIER_ORDER: Tier[] = ["SSS", "SS", "S+", "S", "A", "B", "C"];

export function sortByOverallTier(list: Character[]): Character[] {
  return [...list].sort(
    (a, b) =>
      TIER_ORDER.indexOf(a.tier.overall) - TIER_ORDER.indexOf(b.tier.overall),
  );
}

export function getCharactersUsingGear(gearSlug: string): Character[] {
  return characters.filter(
    (c) =>
      c.build.weaponSlug === gearSlug ||
      c.build.trinketSlug === gearSlug ||
      c.build.tarotSlug === gearSlug,
  );
}

/** How many character builds equip each gear slug. */
export function getGearUsageCounts(): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const c of characters) {
    for (const s of [
      c.build.weaponSlug,
      c.build.trinketSlug,
      c.build.tarotSlug,
    ]) {
      counts[s] = (counts[s] ?? 0) + 1;
    }
  }
  return counts;
}

